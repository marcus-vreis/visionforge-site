# NOTE (Windows/ADR-030): a Dataset class defined in THIS file cannot be sent
# to DataLoader workers — spawn re-imports the dataset's module by name, and
# task files are loaded from a path, not an importable package. Keep
# num_workers=0 here, or define your Dataset in an installed package and use
# cfg.data.num_workers.
class SyntheticDataset(Dataset):
    """TODO: replace with your Dataset reading real files from cfg.data.base_dir."""

    def __init__(self, n: int, seed: int) -> None:
        gen = torch.Generator().manual_seed(seed)
        self.x = torch.randn(n, 8, generator=gen)
        # A fixed linear rule as target, so the demo loss actually drops.
        self.y = self.x @ torch.linspace(-1.0, 1.0, 8).unsqueeze(1)

    def __len__(self) -> int:
        return len(self.x)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor]:
        return self.x[idx], self.y[idx]


@register_task(
    key="research_method",
    label="Research method",
    accent="#2dd4bf",  # tab color, #rrggbb — pick your own
    description="Synthetic regression with an illustrative research penalty",
    # Every metric compute_metrics returns, mapped to its direction —
    # "lower" (errors) or "higher" (scores). Drives ranking and plots.
    metrics={"mae": "lower"},
    primary_metric="mae",  # selects the best checkpoint + report headline
)
class ResearchMethodTask(TaskSpec[ResearchMethodConfig]):
    """Level 1 custom task: four hooks, the engine owns the training loop."""

    Config = ResearchMethodConfig

    def build_model(self, cfg: ResearchMethodConfig) -> nn.Module:
        """Return a freshly-initialized model — any nn.Module works."""
        # TODO: your architecture here.
        return nn.Sequential(
            nn.Linear(8, cfg.hidden_units),
            nn.ReLU(),
            nn.Linear(cfg.hidden_units, 1),
        )

    def build_loaders(self, cfg: ResearchMethodConfig):
        """Return ``(train_loader, val_loader, test_loader_or_None)``."""
        # TODO: build real loaders from cfg.data.base_dir.
        train = SyntheticDataset(cfg.n_samples, seed=cfg.training.seed)
        val = SyntheticDataset(max(cfg.n_samples // 4, 8), seed=cfg.training.seed + 1)

        def _loader(ds: SyntheticDataset, shuffle: bool) -> DataLoader:
            # num_workers=0: see the SyntheticDataset note above (ADR-030).
            return DataLoader(
                ds, batch_size=cfg.training.batch_size, shuffle=shuffle, num_workers=0
            )

        return (
            _loader(train, shuffle=True),
            _loader(val, shuffle=False),
            None,  # a test loader here is also reported, as test_<metric>
        )

    def compute_loss(
        self, model: nn.Module, batch: tuple, cfg: ResearchMethodConfig
    ) -> torch.Tensor:
        """One batch -> scalar loss. Move the batch to the model's device."""
        device = next(model.parameters()).device
        inputs, targets = (t.to(device) for t in batch)
        # TODO: your loss here.
        fit = nn.functional.mse_loss(model(inputs), targets)
        penalty = torch.cat([p.flatten() for p in model.parameters()]).square().mean()
        return fit + cfg.research_weight * penalty

    def compute_metrics(
        self, model: nn.Module, loader: DataLoader, cfg: ResearchMethodConfig
    ) -> dict[str, float]:
        """Evaluate over ``loader`` -> {name: value} matching @register_task."""
        device = next(model.parameters()).device
        errors: list[torch.Tensor] = []
        with torch.no_grad():
            for inputs, targets in loader:
                pred = model(inputs.to(device))
                errors.append((pred - targets.to(device)).abs().flatten().cpu())
        # TODO: your metrics here (keys must match the declaration above).
        return {"mae": torch.cat(errors).mean().item()}
